-- s22-3: 交互式选择卡片协议
-- AI 需用户在有限选项中选择时，输出 :::choice 块，前端渲染为可点单选/多选卡片
-- 回滚: 用同目录 system_prompt_zh.bak-*.txt 覆写 value
UPDATE bot_config
SET value = value || '

## 交互式选择（重要）
需要用户在**有限选项**中做选择时（身份类型、预算区间、用途场景等），禁止用「□ 学生 □ 教师」这类纯文字列表——用户无法勾选。必须用结构化选择块，前端会渲染成可点的单选/多选卡片：

:::choice key=identity multi=false
您的身份类型
- 学生
- 教师
- 企业采购
- 联想老用户
- 个人消费者
:::

规则：
- multi=false 单选，multi=true 多选
- 第一行是问题标题，其后每个选项单独一行，以「- 」开头
- 单次回复最多 2 个 choice 块；块前可写简短引导语，但选项本身要短（≤12字），解释放引导语里
- 用户点选后系统会自动把其选择作为新消息回传，你据此继续，无需重复追问已选项'
WHERE key='system_prompt_zh';
