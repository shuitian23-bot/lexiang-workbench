import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = process.env.PERMISSION_QA_BASE_URL || 'http://127.0.0.1:5174/admin-vue'
const output = path.join(os.tmpdir(), 'organization-members-qa')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const errors = []
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 720 } })
  await context.route('**/api/admin/me', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{}' }))
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}/agent/permissions?module=orgs`)
  await page.locator('.current-card .org-chart-detail-btn').click()
  const detail = page.locator('.org-detail-modal')
  const memberDialog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: /^(添加|编辑)组织成员$/ }) })
  const field = text => memberDialog.locator('label').filter({ hasText: text }).locator('input, select')
  const row = account => detail.locator('tbody tr').filter({ hasText: account })
  const state = () => page.locator('.permission-page-vue').evaluate(el => JSON.parse(JSON.stringify(el.__vueParentComponent.setupState.organizations)))
  const baseline = await state()
  await detail.getByRole('button', { name: '添加成员', exact: true }).click()
  await memberDialog.getByRole('heading', { name: '添加组织成员' }).waitFor()
  assert.equal(await field('姓名').inputValue(), '')
  await memberDialog.getByRole('button', { name: '确认添加' }).click()
  await memberDialog.getByText('请填写成员姓名。', { exact: true }).waitFor()
  await memberDialog.getByText('请填写成员账号。', { exact: true }).waitFor()
  await field('姓名').fill('成员恢复测试')
  await field('账号').fill('guanfeng2')
  await memberDialog.getByRole('button', { name: '确认添加' }).click()
  await memberDialog.getByText('该成员已在当前组织中。', { exact: true }).waitFor()
  assert.deepEqual(await state(), baseline)
  await field('账号').fill('qa-member')
  await page.screenshot({ path: path.join(output, 'add-member.png') })
  await memberDialog.getByRole('button', { name: '取消', exact: true }).click()
  assert.deepEqual(await state(), baseline)
  await detail.getByRole('button', { name: '添加成员', exact: true }).click()
  await field('姓名').fill('成员恢复测试')
  await field('账号').fill('qa-member')
  await memberDialog.getByRole('button', { name: '确认添加' }).click()
  await row('qa-member').waitFor()
  assert.equal((await state())[0].memberCount, baseline[0].memberCount + 1)
  await row('qa-member').getByRole('button', { name: '编辑', exact: true }).click()
  assert.equal(await field('账号').inputValue(), 'qa-member')
  await field('姓名').fill('取消的修改')
  await page.keyboard.press('Escape')
  await memberDialog.waitFor({ state: 'detached' })
  assert.equal(await detail.isVisible(), true)
  assert.match(await row('qa-member').innerText(), /成员恢复测试/)
  await row('qa-member').getByRole('button', { name: '编辑', exact: true }).click()
  await field('组织角色').selectOption({ label: '协作人' })
  await field('姓名').fill('成员恢复测试已更新')
  await memberDialog.getByRole('button', { name: '保存', exact: true }).click()
  assert.match(await row('qa-member').innerText(), /协作人/)
  const beforeMove = await state()
  await row('qa-member').getByRole('button', { name: '编辑', exact: true }).click()
  await field('所属组织').selectOption({ label: 'AI 平台' })
  await memberDialog.getByRole('button', { name: '保存', exact: true }).click()
  await detail.getByRole('heading', { name: 'AI 平台', exact: true }).waitFor()
  const moved = await state()
  const target = moved[0].children.find(org => org.name === 'AI 平台')
  assert.equal(moved[0].members.some(m => m.account === 'qa-member'), false)
  assert.equal(moved[0].memberCount, baseline[0].memberCount)
  assert.equal(target.memberCount, baseline[0].children.find(org => org.id === target.id).memberCount + 1)
  assert.equal(target.members.filter(m => m.account === 'qa-member').length, 1)
  assert.deepEqual(moved[0].children.filter(org => org.id !== target.id), beforeMove[0].children.filter(org => org.id !== target.id))
  await page.screenshot({ path: path.join(output, 'member-actions.png') })
  page.once('dialog', dialog => dialog.dismiss())
  await row('qa-member').getByRole('button', { name: '移除', exact: true }).click()
  assert.deepEqual(await state(), moved)
  page.once('dialog', async dialog => { assert.match(dialog.message(), /确认将/); await dialog.accept() })
  await row('qa-member').getByRole('button', { name: '移除', exact: true }).click()
  await row('qa-member').waitFor({ state: 'detached' })
  const removed = (await state())[0].children.find(org => org.id === target.id)
  assert.deepEqual(removed.members, baseline[0].children.find(org => org.id === target.id).members)
  assert.equal(removed.memberCount, removed.members.length)
  for (const member of [...removed.members]) {
    page.once('dialog', dialog => dialog.accept())
    await row(member.account).getByRole('button', { name: '移除', exact: true }).click()
  }
  await detail.getByText('当前组织还没有成员', { exact: true }).waitFor()
  await detail.getByRole('button', { name: '添加成员', exact: true }).click()
  await field('姓名').fill('空组织新成员')
  await field('账号').fill('qa-empty')
  await memberDialog.getByRole('button', { name: '确认添加' }).click()
  await row('qa-empty').waitFor()
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ result: 'passed', scenarios: ['add', 'required', 'duplicate', 'cancel', 'edit', 'move', 'remove-confirm', 'empty', 'nested-Escape'], screenshots: output, errors }, null, 2))
} finally {
  await browser.close()
}
