import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'))
const origin = process.env.REVIEW_QA_ORIGIN || 'http://127.0.0.1:19449'
assert.match(origin, /^http:\/\/(127\.0\.0\.1|localhost):\d+$/)
const output = process.env.REVIEW_QA_OUTPUT || '/private/tmp/review-management-browser'
mkdirSync(output, { recursive: true })
const report = { cases: [], errors: [], unexpectedRequests: [], passed: false }
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', timeout: 15000 })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' })
  await context.route('**/*', route => {
    const request = route.request(), url = new URL(request.url())
    if (url.origin !== origin || !['GET', 'HEAD'].includes(request.method())) {
      report.unexpectedRequests.push({ url: request.url(), method: request.method() })
      return route.abort()
    }
    if (url.pathname.startsWith('/api/')) {
      const body = url.pathname === '/api/admin/me' ? { admin: { username: 'review-poc-qa' } }
        : url.pathname === '/api/harness/menu' ? { permissions: [], menus: ['dashboard'] } : {}
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) })
    }
    return route.continue()
  })
  const page = await context.newPage()
  page.setDefaultTimeout(8000)
  page.on('pageerror', error => report.errors.push(error.message))
  await page.goto(origin + '/admin-vue/reviews/summary', { waitUntil: 'domcontentloaded' })
  await page.getByRole('heading', { name: '评价总结', exact: true, level: 1 }).waitFor()
  await page.locator('#sidebar-nav').getByText('评价管理', { exact: true }).waitFor()
  report.cases.push('Authenticated direct route and first-level menu are visible')
  const reviewsMenu = page.locator('.nav-group[data-group="reviews"]')
  assert.deepEqual(await reviewsMenu.locator('.nav-sub .nav-item').allTextContents().then(items => items.map(text => text.trim())), ['评价总结', '辅助生成'])
  assert.deepEqual(await page.locator('#sidebar-nav .nav-group').evaluateAll(nodes => nodes.map(node => node.dataset.group)), ['dashboard', 'geo', 'employee', 'lead', 'order', 'advertising', 'aiinspect', 'reviews'])
  report.cases.push('Exactly two review menu children; existing default menu labels and order retained')

  const summary = page.locator('.review-summary-page')
  const summaryRows = summary.locator('tbody tr')
  assert.equal(await summaryRows.count(), 3)
  await summary.getByRole('button', { name: '下一页', exact: true }).click()
  await summaryRows.filter({ hasText: '1056585' }).waitFor()
  assert.equal(await summaryRows.count(), 1)
  await summary.getByRole('button', { name: '上一页', exact: true }).click()
  assert.equal(await summaryRows.count(), 3)
  await summary.getByRole('button', { name: '查看总结', exact: true }).first().click()
  await page.getByRole('dialog', { name: '评价总结详情' }).waitFor()
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => Boolean(document.activeElement?.closest('[role="dialog"]'))), true)
  await page.keyboard.press('Escape')
  await page.getByRole('dialog', { name: '评价总结详情' }).waitFor({ state: 'hidden' })
  assert.equal(await page.locator('#app').getAttribute('inert'), null)
  report.cases.push('Summary pagination changes displayed records; detail focus stays inside and Escape restores page')

  await summary.getByLabel('开始日期', { exact: true }).fill('2026-09-09')
  await summary.getByLabel('结束日期', { exact: true }).fill('2026-09-09')
  await summary.getByRole('button', { name: '查询', exact: true }).click()
  await summaryRows.filter({ hasText: '1056598' }).waitFor()
  assert.equal(await summaryRows.count(), 1)
  await summary.getByLabel('开始日期', { exact: true }).fill('2026-09-11')
  await summary.getByRole('button', { name: '查询', exact: true }).click()
  await summary.getByRole('alert').filter({ hasText: '开始日期不能晚于结束日期' }).waitFor()
  assert.equal(await summaryRows.count(), 1)
  await summary.getByRole('button', { name: '重置', exact: true }).click()
  const summaryDownloadPromise = page.waitForEvent('download')
  await summary.getByRole('button', { name: '导出', exact: true }).click()
  const summaryDownload = await summaryDownloadPromise
  const summaryCsv = readFileSync(await summaryDownload.path(), 'utf8')
  assert.equal(summaryCsv.split('\r\n').length, 5)
  assert.match(summaryCsv, /1056585/)
  await summary.getByPlaceholder('商品名称', { exact: true }).fill('不存在的商品')
  await summary.getByRole('button', { name: '查询', exact: true }).click()
  await summary.getByText('暂无匹配记录', { exact: true }).waitFor()
  assert.equal(await summary.getByRole('button', { name: '导出', exact: true }).isDisabled(), true)
  await summary.getByRole('button', { name: '重置', exact: true }).click()
  await page.screenshot({ path: path.join(output, 'summary-query.png'), fullPage: true })
  report.cases.push('Summary inclusive date filter, invalid range, empty state, reset and all-filtered-records CSV export')

  const mainTabs = page.getByRole('tablist', { name: '评估视图', exact: true })
  await mainTabs.getByRole('tab', { name: '标注', exact: true }).click()
  const mark = page.locator('.rse-quality-section')
  assert.equal(await mark.getByRole('button', { name: '合格', exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: '查看抽样规则', exact: true }).click()
  await page.getByRole('dialog', { name: '抽样规则', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  for (const button of await mark.getByRole('button', { name: '通过', exact: true }).all()) await button.click()
  await mark.getByRole('button', { name: '合格', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.rse-progress-title strong')?.textContent === '2')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.rse-progress-title strong')?.textContent === '1')
  await mark.getByRole('button', { name: '不通过', exact: true }).first().click()
  assert.equal(await mark.getByRole('button', { name: '不合格', exact: true }).isDisabled(), true)
  await mark.locator('select').selectOption('存在无依据或虚假事实')
  await mark.getByRole('button', { name: '不合格', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.rse-progress-title strong')?.textContent === '2')
  report.cases.push('Quality marking requires all checks, supports undo and requires reason for failed checks')

  await mainTabs.getByRole('tab', { name: /^处置/ }).click()
  assert.equal(await page.locator('.rse-table-actions .rse-muted-action').count(), 0)
  await page.getByLabel('当前角色', { exact: true }).selectOption('仲裁员')
  await page.getByRole('button', { name: '裁决', exact: true }).click()
  await page.getByRole('dialog', { name: '仲裁裁决', exact: true }).getByRole('button', { name: '成立，确认下线', exact: true }).click()
  const firstTicket = page.locator('.rse-queue-panel tbody tr').filter({ hasText: 'QC-260910-01' })
  await firstTicket.getByText('已下线', { exact: true }).waitFor()
  await page.getByLabel('当前角色', { exact: true }).selectOption('开发')
  await firstTicket.getByRole('button', { name: '开发确认', exact: true }).click()
  const devDialog = page.getByRole('dialog', { name: '开发确认', exact: true })
  await devDialog.getByRole('button', { name: '确认无误，转产品', exact: true }).click()
  assert.equal(await devDialog.isVisible(), true)
  await devDialog.locator('textarea').fill('POC 验证：补充事实校验后复核通过')
  await devDialog.getByRole('button', { name: '确认无误，转产品', exact: true }).click()
  await firstTicket.getByText('待产品确认', { exact: true }).waitFor()
  await page.getByLabel('当前角色', { exact: true }).selectOption('产品')
  await firstTicket.getByRole('button', { name: '产品确认', exact: true }).click()
  await page.getByRole('dialog', { name: '产品确认上线', exact: true }).getByRole('button', { name: /确认.*上线/ }).click()
  await firstTicket.getByText('已上线', { exact: true }).waitFor()
  report.cases.push('POC queue actions follow local role; arbitration, required developer cause and product confirmation advance seed ticket')

  await mainTabs.getByRole('tab', { name: '分析', exact: true }).click()
  await page.locator('.review-chart canvas').first().waitFor()
  await page.getByRole('button', { name: '近 7 天', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '近 7 天', exact: true }).getAttribute('aria-pressed'), 'true')
  const chartDownloadPromise = page.waitForEvent('download')
  await page.locator('.review-analysis-panel').getByRole('button', { name: '导出', exact: true }).click()
  assert.match(readFileSync(await (await chartDownloadPromise).path(), 'utf8'), /评价总结分析/)
  await page.screenshot({ path: path.join(output, 'summary-analysis.png'), fullPage: true })
  report.cases.push('Summary analysis renders ECharts, switches range and exports analysis')

  await reviewsMenu.getByRole('button', { name: '辅助生成', exact: true }).click()
  await page.getByRole('heading', { name: '辅助生成', exact: true, level: 1 }).waitFor()
  const assist = page.locator('.assist-generation-page')
  const assistRows = assist.locator('.ag-table tbody tr')
  assert.equal(await assistRows.count(), 3)
  await assist.getByRole('button', { name: '下一页', exact: true }).click()
  await assistRows.filter({ hasText: '135****3366' }).waitFor()
  await assist.getByRole('button', { name: '查看草稿', exact: true }).first().click()
  await page.getByRole('dialog', { name: 'AI 草稿详情', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await assist.getByRole('button', { name: /展开更多条件/ }).click()
  await assist.getByLabel('开始日期', { exact: true }).fill('2026-09-09')
  await assist.getByLabel('结束日期', { exact: true }).fill('2026-09-09')
  await assist.getByRole('button', { name: '查询', exact: true }).click()
  await assist.getByText('暂无匹配记录', { exact: true }).waitFor()
  assert.equal(await assist.getByRole('button', { name: '导出', exact: true }).isDisabled(), true)
  await assist.getByRole('button', { name: '重置', exact: true }).click()
  await assist.getByLabel('结果状态', { exact: true }).selectOption('生成前拦截')
  await assist.getByRole('button', { name: '查询', exact: true }).click()
  await assistRows.filter({ hasText: '186****5510' }).waitFor()
  assert.equal(await assistRows.count(), 1)
  const assistDownloadPromise = page.waitForEvent('download')
  await assist.getByRole('button', { name: '导出', exact: true }).click()
  const assistCsv = readFileSync(await (await assistDownloadPromise).path(), 'utf8')
  assert.equal(assistCsv.split('\r\n').length, 2)
  assert.match(assistCsv, /186\*\*\*\*5510/)
  assert.doesNotMatch(assistCsv, /18666665510/)
  await assist.getByRole('button', { name: '重置', exact: true }).click()
  await page.screenshot({ path: path.join(output, 'assist-query.png'), fullPage: true })
  report.cases.push('Assist pagination, draft dialog, extra filters, date empty state and filtered CSV use masked accounts')

  await page.getByRole('tablist', { name: '辅助生成视图', exact: true }).getByRole('tab', { name: '分析', exact: true }).click()
  await page.locator('.review-chart canvas').first().waitFor()
  await page.locator('.ra-source-filter select').selectOption('商城')
  await page.getByRole('button', { name: '近 15 天', exact: true }).click()
  await page.screenshot({ path: path.join(output, 'assist-analysis.png'), fullPage: true })
  await page.getByRole('button', { name: '打开 AI 助手', exact: true }).click()
  const handle = await page.locator('#ai-resize-handle').boundingBox()
  assert.ok(handle)
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 100)
  await page.mouse.down()
  await page.mouse.move(handle.x - 140, handle.y + 100, { steps: 10 })
  await page.mouse.up()
  for (const width of [1440, 1280]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.screenshot({ path: path.join(output, `assist-analysis-${width}.png`), fullPage: true })
    report.layouts ||= []
    report.layouts.push(await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth, overflow: [...document.querySelectorAll('body *')].filter(node => node.getBoundingClientRect().right > innerWidth + 1).slice(0, 15).map(node => ({ tag: node.tagName, className: node.className, right: node.getBoundingClientRect().right, width: node.getBoundingClientRect().width })) })))
    await page.waitForFunction(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
  }
  report.cases.push('Assist analysis source/range controls and 1440/1280 layouts with expanded/resized Agent do not add page-level horizontal scrolling')
  report.limitations = ['Existing workbench shell has a 1280px desktop minimum width, unchanged by this task; no mobile support claim.', 'Data, roles and workflows are attachment POC seeds; no real backend integration.']
  assert.deepEqual(report.errors, [])
  assert.deepEqual(report.unexpectedRequests, [])
  report.passed = true
  await context.close()
} catch (error) {
  report.failure = error.stack || String(error)
  throw error
} finally {
  await browser.close()
  writeFileSync(path.join(output, 'report.json'), JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
}
